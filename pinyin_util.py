def get_pinyin_initials(text: str) -> str:
    """获取字符串的拼音首字母序列（仅汉字+字母数字参与）"""
    result = []
    for ch in text:
        if '\u4e00' <= ch <= '\u9fff':
            result.append(_PINYIN_MAP.get(ch, ch.upper()))
        elif ch.isalpha():
            result.append(ch.upper())
        elif ch.isdigit():
            result.append(ch)
    return ''.join(result)

def _is_subsequence(query: str, target: str) -> bool:
    """判断 query 是否是 target 的子序列（跳跃匹配）"""
    i = 0
    for c in target:
        if i < len(query) and c == query[i]:
            i += 1
    return i == len(query)

def match_product(query: str, name: str) -> bool:
    """
    产品搜索匹配：
    1. 查询为空 → 全部匹配
    2. 中文包含匹配（如输入"芝士"）
    3. 拼音首字母连续匹配（如 qm → 全麦）
    4. 拼音首字母跳跃匹配（如 hz → 黑芝麻/红豆）
    """
    if not query:
        return True
    q = query.upper().strip()
    # 中文包含
    if any(ord(c) > 127 for c in query) and query in name:
        return True
    # 英文/拼音匹配
    py = get_pinyin_initials(name)
    if q in py:
        return True
    # 跳跃子序列匹配
    return _is_subsequence(q, py)

